package com.nightclip.app.core

import android.content.Context
import android.os.Build
import android.provider.Settings
import android.util.Log
import com.nightclip.app.BuildConfig
import com.nightclip.app.logic.DbKeyProvider
import com.nightclip.app.logic.KeyCorruptedException
import com.nightclip.app.logic.Strings
import com.nightclip.app.platform.KeystoreCipher
import com.nightclip.core.mobile.Core
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.flow.MutableSharedFlow
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.SharedFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asSharedFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.withContext
import kotlinx.coroutines.withTimeoutOrNull
import kotlinx.coroutines.channels.BufferOverflow
import org.json.JSONObject
import java.io.File

/** Where the core is in its start-up. */
sealed interface CoreState {
    data object Starting : CoreState
    data object Ready : CoreState

    /** [code] is a core error code (KEY_INVALID, DB_UNAVAILABLE …) or a local one (KEY_CORRUPT …). */
    data class Failed(val code: String, val message: String, val canReset: Boolean) : CoreState
}

/**
 * Process-wide owner of the Go core (docs/architecture.md §2.3, shell-guide §4.1).
 * Started once from [com.nightclip.app.ClipBridgeApp]; exactly ONE thread (the event pump)
 * calls `Core.nextEvent` and publishes to [events]; every screen, service and receiver
 * consumes that SharedFlow. Nothing here shuts the core down: the process owns it.
 *
 * `com.nightclip.core.mobile.Core` is generated by `make aar`.
 */
object CoreHost {
    private const val TAG = "ClipBridge"

    private val _state = MutableStateFlow<CoreState>(CoreState.Starting)
    val state: StateFlow<CoreState> = _state.asStateFlow()

    // Slow collectors lose the oldest events instead of blocking the pump; screens re-read
    // state from the core when they resume, so a dropped event is never fatal.
    private val _events = MutableSharedFlow<CoreEvent>(extraBufferCapacity = 512, onBufferOverflow = BufferOverflow.DROP_OLDEST)
    val events: SharedFlow<CoreEvent> = _events.asSharedFlow()

    @Volatile private var core: Core? = null
    private var pump: Thread? = null
    private var starting = false

    val isReady: Boolean get() = core != null

    /** Idempotent. Runs key loading and `Core.init` on a background thread. */
    @Synchronized
    fun start(context: Context) {
        if (core != null || starting) return
        starting = true
        _state.value = CoreState.Starting
        val app = context.applicationContext
        Thread({ doStart(app) }, "clipbridge-start").start()
    }

    private fun doStart(app: Context) {
        try {
            val dataDir = File(app.filesDir, "clipbridge").apply { mkdirs() }
            val loaded = try {
                DbKeyProvider(dataDir, KeystoreCipher()).loadOrCreate()
            } catch (e: KeyCorruptedException) {
                return fail("KEY_CORRUPT", Strings.ERR_KEY_CORRUPT)
            } catch (e: Exception) {
                return fail("KEYSTORE_UNAVAILABLE", Strings.ERR_KEY_STORE)
            }
            val config = JSONObject()
                .put("data_dir", dataDir.absolutePath)
                .put("db_key_b64", loaded.keyB64)
                .put("device_name", deviceName(app))
                .put("platform", "android")
                .put("listen", false) // Android only dials out (docs/architecture.md §4.1)
                .put("app_version_code", BuildConfig.CB_VERSION_CODE) // 0 in dev builds: updates off
                .put("app_version_name", BuildConfig.CB_VERSION_NAME)
                .put("update_url", BuildConfig.CB_UPDATE_URL)
            // gomobile turns Go's NewCore() into the Java constructor Core().
            val c = Core()
            c.init(config.toString())
            synchronized(this) {
                core = c
                starting = false
            }
            startPump(c)
            _state.value = CoreState.Ready
            Log.i(TAG, "core started (key migrated=${loaded.migrated})")
        } catch (e: Exception) {
            // Core.init throws with the Go error text "CODE: message".
            val code = ErrorMessages.codeFromInitFailure(e.message)
            fail(code, ErrorMessages.forCode(code))
        }
    }

    private fun fail(code: String, message: String) {
        Log.e(TAG, "core start failed: $code")
        synchronized(this) { starting = false }
        _state.value = CoreState.Failed(code, message, ErrorMessages.isResettable(code))
    }

    private fun deviceName(context: Context): String {
        val user = try {
            Settings.Global.getString(context.contentResolver, "device_name")
        } catch (e: Exception) {
            null
        }
        return user?.trim()?.takeIf { it.isNotEmpty() } ?: Build.MODEL.ifBlank { "Android" }
    }

    /** The single event pump of the process (shell-guide §1). */
    private fun startPump(c: Core) {
        pump = Thread({
            while (core === c) {
                try {
                    val raw = c.nextEvent(1000)
                    if (raw.isNullOrEmpty()) continue
                    val ev = CoreEvent.parse(raw) ?: continue
                    Log.d(TAG, "event type=${ev.type} id=${ev.logId}")
                    _events.tryEmit(ev)
                } catch (e: Throwable) {
                    Log.w(TAG, "event pump: ${e.javaClass.simpleName}")
                    try {
                        Thread.sleep(500)
                    } catch (_: InterruptedException) {
                        return@Thread
                    }
                }
            }
        }, "clipbridge-events").also {
            it.isDaemon = true
            it.start()
        }
    }

    /** Blocking facade call; callers must already be on a background thread. */
    fun callBlocking(method: String, params: JSONObject = JSONObject()): Reply {
        val c = core ?: return Reply.notReady()
        return try {
            Reply.parse(c.call(method, params.toString()))
        } catch (e: Throwable) {
            Log.w(TAG, "call $method failed: ${e.javaClass.simpleName}")
            Reply.failure("INTERNAL", "call failed")
        }
    }

    /**
     * Waits (without blocking a thread) until start-up finished; true only if the core is running.
     * Receivers and activities launched cold use this because the core starts asynchronously.
     */
    suspend fun awaitReady(timeoutMs: Long = 10_000): Boolean {
        if (core != null) return true
        val final = withTimeoutOrNull(timeoutMs) { state.first { it !is CoreState.Starting } }
        return final is CoreState.Ready
    }

    /** Facade call on the IO dispatcher; never blocks the caller's thread. Waits for a starting core. */
    suspend fun call(method: String, params: JSONObject = JSONObject()): Reply {
        if (core == null && !awaitReady()) return Reply.notReady()
        return withContext(Dispatchers.IO) { callBlocking(method, params) }
    }

    /**
     * Wipes the local data directory and the Keystore key and starts again with a new identity.
     * Only valid after a failed start (the core object is not running then).
     */
    fun resetData(context: Context) {
        val app = context.applicationContext
        Thread({
            synchronized(this) {
                if (core != null) return@Thread // a running core must not lose its files
                starting = true
            }
            _state.value = CoreState.Starting
            try {
                File(app.filesDir, "clipbridge").deleteRecursively()
                KeystoreCipher().deleteKey()
            } catch (e: Exception) {
                Log.w(TAG, "reset: ${e.javaClass.simpleName}")
            }
            doStart(app)
        }, "clipbridge-reset").start()
    }
}
