namespace ClipBridge.Mac.Platform;

public enum PasteReadStatus { Ok, Empty, Excluded }

public readonly record struct PasteRead(PasteReadStatus Status, string Text);

/// <summary>
/// The general NSPasteboard, plain text only (like the Windows shell, which handles CF_UNICODETEXT only).
/// macOS has no change notification: <see cref="ChangeCount"/> is polled (docs/plan-macos.md §3.2).
/// </summary>
public static class MacPasteboard
{
    private const string TypeText = "public.utf8-plain-text";

    // nspasteboard.org markers: password managers flag their copies (never sent), and our own writes
    // are flagged transient so clipboard managers do not keep received items.
    private const string TypeConcealed = "org.nspasteboard.ConcealedType";
    private const string TypeTransient = "org.nspasteboard.TransientType";
    private const string TypeAutoGenerated = "org.nspasteboard.AutoGeneratedType";

    private const long CurrentHostOnly = 1; // NSPasteboardContentsCurrentHostOnly: keep it off Universal Clipboard

    private static IntPtr General() => ObjC.Send(ObjC.Class("NSPasteboard"), ObjC.Sel("generalPasteboard"));

    /// <summary>Increases on every change by any application. Cheap: no content is read.</summary>
    public static uint ChangeCount() => ObjC.Pool(() => unchecked((uint)ObjC.SendLong(General(), ObjC.Sel("changeCount"))));

    public static PasteRead ReadText() => ObjC.Pool(() =>
    {
        var pb = General();
        var types = ObjC.Send(pb, ObjC.Sel("types"));
        if (ObjC.ArrayContainsString(types, TypeConcealed) || ObjC.ArrayContainsString(types, TypeTransient)
            || ObjC.ArrayContainsString(types, TypeAutoGenerated))
            return new PasteRead(PasteReadStatus.Excluded, "");
        var text = ObjC.FromNSString(ObjC.Send(pb, ObjC.Sel("stringForType:"), ObjC.NSString(TypeText)));
        return string.IsNullOrEmpty(text) ? new PasteRead(PasteReadStatus.Empty, "") : new PasteRead(PasteReadStatus.Ok, text);
    });

    /// <summary>
    /// Puts the image file on the clipboard as an NSImage (pastes as a picture in other apps, local only).
    /// Returns the new change count, or null when the file cannot be read as an image.
    /// </summary>
    public static uint? WriteImageFile(string path) => ObjC.Pool<uint?>(() =>
    {
        var url = ObjC.Send(ObjC.Class("NSURL"), ObjC.Sel("fileURLWithPath:"), ObjC.NSString(path));
        var image = ObjC.Send(ObjC.Send(ObjC.Class("NSImage"), ObjC.Sel("alloc")), ObjC.Sel("initWithContentsOfURL:"), url);
        if (image == IntPtr.Zero) return null;
        try
        {
            var pb = General();
            ObjC.SendLongArg(pb, ObjC.Sel("prepareForNewContentsWithOptions:"), CurrentHostOnly);
            var items = ObjC.Send(ObjC.Class("NSArray"), ObjC.Sel("arrayWithObject:"), image);
            if (!ObjC.SendBool(pb, ObjC.Sel("writeObjects:"), items, IntPtr.Zero)) return null;
            return unchecked((uint)ObjC.SendLong(pb, ObjC.Sel("changeCount")));
        }
        finally { ObjC.Send(image, ObjC.Sel("release")); }
    });

    /// <summary>Replaces the clipboard with <paramref name="text"/>; returns the new change count, or null on failure.</summary>
    public static uint? WriteText(string text, bool sensitive) => ObjC.Pool<uint?>(() =>
    {
        var pb = General();
        ObjC.SendLongArg(pb, ObjC.Sel("prepareForNewContentsWithOptions:"), CurrentHostOnly);
        var ok = ObjC.SendBool(pb, ObjC.Sel("setString:forType:"), ObjC.NSString(text), ObjC.NSString(TypeText));
        if (!ok) return null;
        ObjC.SendBool(pb, ObjC.Sel("setString:forType:"), ObjC.NSString(""), ObjC.NSString(TypeTransient));
        if (sensitive) ObjC.SendBool(pb, ObjC.Sel("setString:forType:"), ObjC.NSString(""), ObjC.NSString(TypeConcealed));
        return unchecked((uint)ObjC.SendLong(pb, ObjC.Sel("changeCount")));
    });
}
